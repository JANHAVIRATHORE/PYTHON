'''Perform addition, subtraction, multiplication, division, floor division, 
   modulus, and exponentiation on two numbers input by the user.'''

print("\nLet's perform Arithmetic Operations:\n");
num1=int(input("Enter first value:"));
num2=int(input("Enter second value:"));

print("\nAddition of two numbers is:",num1+num2);
print("\nSubtraction of two numbers is:",num1-num2);
print("\nMultiplication of two numbers is:",num1*num2);
print("\nDivision of two numbers is:",num1/num2);
print("\nFloor Division of two numbers is:",num1//num2);
print("\nModulus of two numbers is:",num1%num2);
print("\nExponentiation of two numbers is:",num1**num2);